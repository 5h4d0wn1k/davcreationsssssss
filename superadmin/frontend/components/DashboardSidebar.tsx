interface SidebarMenuItemProps {
  item: MenuItem;
  isOpen: boolean;
  onToggle: () => void;
  level?: number;
}

const SidebarMenuItem: React.FC<SidebarMenuItemProps> = ({ item, isOpen, onToggle, level = 0 }) => {
  const hasChildren = item.children && item.children.length > 0;
  const paddingLeft = level === 0 ? 'pl-4' : `pl-${4 + level * 4}`;

  if (hasChildren) {
    return (
      <div>
        <button
          onClick={onToggle}
          className={`w-full flex items-center space-x-3 px-4 py-3 text-left hover:bg-accent transition-colors duration-200 ${paddingLeft}`}
        >
          <span className="text-muted">{item.icon}</span>
          <span className="flex-1 text-foreground font-medium">{item.label}</span>
          <svg
            className={`w-4 h-4 text-muted transition-transform duration-200 ${isOpen ? 'rotate-90' : ''}`}
            fill="none"
            stroke="currentColor"
            viewBox="0 0 24 24"
          >
            <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M9 5l7 7-7 7" />
          </svg>
        </button>

        {isOpen && (
          <div className="ml-4">
            {item.children!.map((child) => (
              <SidebarMenuItem
                key={child.id}
                item={child}
                isOpen={false}
                onToggle={() => {}}
                level={level + 1}
              />
            ))}
          </div>
        )}
      </div>
    );
  }

  return (
    <Link
      href={item.href || '#'}
      className={`flex items-center space-x-3 px-4 py-3 hover:bg-accent transition-colors duration-200 ${paddingLeft}`}
    >
      <span className="text-muted">{item.icon}</span>
      <span className="text-foreground font-medium">{item.label}</span>
    </Link>
  );
};

export const DashboardSidebar: React.FC = () => {
  const [openMenus, setOpenMenus] = useState<Set<string>>(new Set());

  const toggleMenu = (menuId: string) => {
    const newOpenMenus = new Set(openMenus);
    if (newOpenMenus.has(menuId)) {
      newOpenMenus.delete(menuId);
    } else {
      newOpenMenus.add(menuId);
    }
    setOpenMenus(newOpenMenus);
  };

  return (
    <aside className="w-64 bg-card border-r border-border flex flex-col h-full">
      {/* Navigation Menu */}
      <nav className="flex-1 p-4 overflow-y-auto">
        <ul className="space-y-1">
          {menuItems.map((item) => (
            <li key={item.id}>
              <SidebarMenuItem
                item={item}
                isOpen={openMenus.has(item.id)}
                onToggle={() => toggleMenu(item.id)}
              />
            </li>
          ))}
        </ul>
      </nav>
    </aside>
  );
};